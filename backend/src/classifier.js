export function calculateLeadScore(text, industry, budget = "") {
  let score = 50;

  // Если сфера входит в 7 целевых отраслей
  if (industry) score += 20;

  // Если упомянут бюджет или договор
  const lowerBudget = (budget || '').toLowerCase();
  if (lowerBudget && !lowerBudget.includes('не указан') && !lowerBudget.includes('договор')) {
    score += 15;
  }

  // Если есть ключевые слова крупных проектов
  const lowerText = text.toLowerCase();
  if (lowerText.includes('промо') || lowerText.includes('cgi') || lowerText.includes('3d') || lowerText.includes('презентац')) {
    score += 10;
  }

  return Math.min(score, 98);
}


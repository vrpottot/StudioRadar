export function checkSpamFilters(text, source = "") {
  const lower = text.toLowerCase();
  const sourceLower = source.toLowerCase();

  // Отсев резюме и исполнителей
  if (RESUME_STOP_WORDS.some(w => lower.includes(w))) {
    return [true, "Предложение услуг фрилансера / соискателя (не заказчик)"];
  }

  // Биржи фриланса
  if (STOP_DOMAINS_FREELANCE.some(d => lower.includes(d) || sourceLower.includes(d))) {
    return [true, "Запрещенная биржа фриланса"];
  }

  // Найм в штат (рутинные сотрудники)
  if (STOP_WORDS_STAFF.some(w => lower.includes(w))) {
    return [true, "Поиск сотрудника в штат"];
  }

  // Рилсы и копеечный монтаж
  if (STOP_WORDS_CHEAP.some(w => lower.includes(w))) {
    return [true, "Мелкий монтаж / копеечный чек"];
  }

  // Обучение
  if (STOP_WORDS_EDUCATION.some(w => lower.includes(w))) {
    return [true, "Инфобизнес / обучение"];
  }

  return [false, null];
}

